test('benefit keeps period, saves string paragraphs and fills the summary from the first text', () => {
  const form = createForm({}, 'benefit')
  assert.equal(form.period, '')
  form.title = ' 十一月体检福利 '; form.period = ' 2026-11-01 至 2026-11-30 '
  form.contentBlocks = [{ type: 'image', url: 'https://example.com/a.jpg', caption: '' }, { type: 'text', title: '', text: '  活动期间到园区体检\n可享受专属服务。这是一段很长的说明文字，用来检查列表摘要会不会只取前六十个字，超过的部分不会出现在列表里。' }, { type: 'text', title: '', text: '' }]
  const saved = serializeForm(form, {}, 'benefit', () => 'u3')
  assert.equal(saved.id, 'benefit-u3')
  assert.equal(saved.kindCode, 'benefit')
  assert.equal(saved.title, '十一月体检福利')
  assert.equal(saved.period, '2026-11-01 至 2026-11-30')
  assert.equal(saved.contentBlocks.length, 2)
  assert.equal(saved.contentBlocks[0].type, 'image')
  assert.equal(saved.paragraphs.length, 1)
  assert.equal(typeof saved.paragraphs[0], 'string')
  assert.equal(saved.summary.length, 60)
  assert.ok(saved.summary.startsWith('活动期间到园区体检 可享受专属服务。'))
  const edited = createForm(saved, 'benefit')
  edited.summary = '  自己写的摘要  '
  assert.equal(serializeForm(edited, saved, 'benefit').summary, '自己写的摘要')
  assert.equal(serializeForm(edited, saved, 'benefit').period, '2026-11-01 至 2026-11-30')
})
test('process seed items keep their id and scene and turn string paragraphs into text blocks', () => {
  const source = { id: 'consult', kindCode: 'process', title: '在线咨询：在客服页面沟通', scene: 1, summary: '', coverImage: '', status: '1', sortOrder: 1, contentVersion: 2, paragraphs: ['第一段', '第二段'], contentBlocks: [{ type: 'text', title: '', text: '第一段' }, { type: 'text', title: '', text: '第二段' }] }
  const form = createForm(source, 'process')
  assert.deepEqual(form.contentBlocks, source.contentBlocks)
  form.contentBlocks.push({ type: 'image', url: 'https://example.com/b.png', caption: '客服页' })
  const saved = serializeForm(form, source, 'process')
  assert.equal(saved.id, 'consult')
  assert.equal(saved.kindCode, 'process')
  assert.equal(saved.scene, 1)
  assert.deepEqual(saved.paragraphs, ['第一段', '第二段'])
  assert.equal(saved.contentBlocks.length, 3)
  assert.equal(saved.summary, '第一段')
  assert.equal(saved.status, '1')
  assert.deepEqual(createForm({ id: 'p', paragraphs: ['甲'] }, 'process').contentBlocks, [{ type: 'text', title: '', text: '甲' }])
})
test('source links must be http or https', () => {
  assert.equal(isWebUrl(''), true)
  assert.equal(isWebUrl('https://www.gov.cn/zhengce/'), true)
  assert.equal(isWebUrl('http://example.com'), true)
  assert.equal(isWebUrl('www.gov.cn'), false)
  assert.equal(isWebUrl('javascript:alert(1)'), false)
})
